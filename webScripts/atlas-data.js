// =========================
// BUILD DATA WITH COORDS
// =========================

const ATLAS_DATA = RAW_SPRITES.map((entry, index) => ({
    ...entry,
    index,
    x: (index % ATLAS_COLUMNS) * TILE_SIZE,
    y: Math.floor(index / ATLAS_COLUMNS) * TILE_SIZE,
    size: TILE_SIZE
}));

// =========================
// GROUPING
// =========================

const ATLAS_GROUPS = {};

ATLAS_DATA.forEach(entry => {
    const group = entry.atlas;

    if (!ATLAS_GROUPS[group]) {
        ATLAS_GROUPS[group] = [];
    }

    ATLAS_GROUPS[group].push(entry);
});

// =========================
// SEARCH
// =========================

function searchAtlas(group, query) {
    const list = ATLAS_GROUPS[group] || [];

    if (!query) return list;

    const q = query.toLowerCase();

    return list.filter(e =>
        e.sprite.toLowerCase().includes(q)
    );
}

// =========================
// LOOKUP
// =========================

function getAtlasEntry(atlas, sprite) {
    return ATLAS_DATA.find(
        e => e.atlas === atlas && e.sprite === sprite
    );
}

// =========================
// EXPORT
// =========================

window.ATLAS_DATA = ATLAS_DATA;
window.ATLAS_GROUPS = ATLAS_GROUPS;
window.searchAtlas = searchAtlas;
window.getAtlasEntry = getAtlasEntry;